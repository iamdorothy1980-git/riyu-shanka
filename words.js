  var MAX_LEN = 14;
  var KEYS = Object.keys(WORDS);

  function tokenize(text) {
    var s = String(text || '');
    var out = [];
    var i = 0;

    function matchAt(pos) {
      var max = Math.min(MAX_LEN, s.length - pos);
      for (var len = max; len >= 1; len--) {
        var sub = s.substr(pos, len);
        if (WORDS[sub]) return sub;
      }
      return null;
    }

    var PARTICLES = 'はがをにのもとかねよへや';

    function hasWordFrom(pos) {
      var max = Math.min(MAX_LEN, s.length - pos);
      for (var len = max; len >= 2; len--) {
        if (WORDS[s.substr(pos, len)]) return true;
      }
      return false;
    }

    while (i < s.length) {
      // 助词后面紧跟一个词时，助词单独成词（避免「は＋い」拼成「はい」）
      if (PARTICLES.indexOf(s.charAt(i)) !== -1 && hasWordFrom(i + 1)) {
        var p = s.charAt(i);
        out.push({ t: p, w: WORDS[p] || null });
        i += 1;
        continue;
      }
      var hit = matchAt(i);
      if (hit) {
        out.push({ t: hit, w: WORDS[hit] });
        i += hit.length;
        continue;
      }
      // 没有命中词库：把连续的未命中字符合并成普通文本
      var j = i + 1;
      while (j < s.length) {
        if (matchAt(j)) break;
        j++;
      }
      out.push({ t: s.slice(i, j), w: null });
      i = j;
    }
    return out;
  }

  window.WORDS = WORDS;
  window.tokenizeJapanese = tokenize;
